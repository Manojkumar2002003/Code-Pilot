class RequirementGenerationRequest(BaseModel):
    """Request contract for initiating an AI-driven requirement generation run."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    project_id: str = Field(..., min_length=1, description="Target project identifier.")
    project_context: ProjectContext
    generation_instructions: str | None = Field(
        default=None,
        max_length=5000,
        description="Optional human-specified focus or scoping instructions.",
    )
    target_categories: list[NFRCategory] = Field(
        default_factory=list,
        description="Optional subset of NFR categories to generate.",
    )
    mode: GenerationMode = Field(
        default=GenerationMode.INITIAL,
        description="Generation mode: initial, refinement, or regeneration.",
    )
    include_user_stories: bool = True
    include_business_rules: bool = True
    include_clarifications: bool = True

    @model_validator(mode="after")
    def validate_project_match(self) -> RequirementGenerationRequest:
        if self.project_context.project_id != self.project_id:
            raise ValueError(
                f"Project ID mismatch in generation request: request targets '{self.project_id}', "
                f"but context belongs to '{self.project_context.project_id}'."
            )
        return self

    def to_llm_request(
        self,
        system_instruction: str | None = None,
        model: str | None = None,
        provider: LLMProviderID | None = None,
        temperature: float | None = None,
    ) -> LLMRequest:
        """Create a provider-independent LLMRequest targeting this generation result schema."""
        default_sys = (
            "You are CodePilot's Requirement Analyst. Analyze the provided project context "
            "and output a structured software requirement specification adhering strictly "
            "to the requested JSON schema. Do not invent unverified facts."
        )
        sys_prompt = system_instruction or default_sys

        user_content_lines = [
            "Please generate a complete requirement specification for the following project context:\n",
            self.project_context.to_prompt_summary(),
        ]
        if self.generation_instructions:
            user_content_lines.append(f"\nAdditional Instructions:\n{self.generation_instructions}")

        user_prompt = "\n".join(user_content_lines)

        return LLMRequest(
            provider=provider,
            model=model,
            system_instruction=sys_prompt,
            messages=[ConversationMessage(role=MessageRole.USER, content=user_prompt)],
            temperature=temperature,
            structured_output=StructuredOutputRequirement(
                json_schema=RequirementGenerationResult.model_json_schema(),
                description="RequirementGenerationResult JSON Schema",
            ),
        )


class RequirementGenerationResult(BaseModel):
    """Complete, validated requirement generation specification output from an AI agent."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    generation_id: str = Field(
        default_factory=lambda: str(uuid.uuid4()),
        description="Unique generation session identifier.",
    )
    project_id: str = Field(..., min_length=1)
    created_at: datetime = Field(default_factory=utc_now)
    summary: str = Field(
        ...,
        min_length=1,
        max_length=5000,
        description="Executive summary of the generated requirement specification.",
    )
    functional_requirements: list[ProposedFunctionalRequirement] = Field(default_factory=list)
    non_functional_requirements: list[ProposedNonFunctionalRequirement] = Field(default_factory=list)
    user_stories: list[ProposedUserStory] = Field(default_factory=list)
    business_rules: list[ProposedBusinessRule] = Field(default_factory=list)
    assumptions: list[ProposedAssumption] = Field(default_factory=list)
    dependencies: list[ProposedDependency] = Field(default_factory=list)
    clarification_questions: list[ClarificationQuestion] = Field(default_factory=list)
    validation_warnings: list[str] = Field(default_factory=list)
    execution_metadata: GenerationExecutionMetadata | None = Field(
        default=None,
        description="Execution and failover telemetry recorded during generation.",
    )

    @field_validator("summary")
    @classmethod
    def validate_summary(cls, value: str) -> str:
        cleaned = value.strip()
        if not cleaned:
            raise ValueError("Generation summary cannot be empty.")
        return cleaned

    @model_validator(mode="after")
    def validate_integrity(self) -> RequirementGenerationResult:
        """Validate ID uniqueness, non-empty content, and referential integrity."""
        # 1. Non-empty check
        total_items = (
            len(self.functional_requirements)
            + len(self.non_functional_requirements)
            + len(self.clarification_questions)
        )
        if total_items == 0:
            raise ValueError(
                "Generation result must contain at least one proposed requirement or clarification question."
            )

        # 2. Unique identifiers check
        seen_ids: dict[str, str] = {}

        def record_id(item_id: str, item_type: str) -> None:
            if item_id in seen_ids:
                raise ValueError(
                    f"Duplicate identifier '{item_id}' detected in generation result: "
                    f"used by {seen_ids[item_id]} and {item_type}."
                )
            seen_ids[item_id] = item_type

        for fr in self.functional_requirements:
            record_id(fr.id, f"Functional Requirement '{fr.title}'")
        for nfr in self.non_functional_requirements:
            record_id(nfr.id, f"Non-Functional Requirement '{nfr.title}'")
        for us in self.user_stories:
            record_id(us.id, f"User Story '{us.title}'")
        for br in self.business_rules:
            record_id(br.id, f"Business Rule '{br.id}'")
        for asm in self.assumptions:
            record_id(asm.id, f"Assumption '{asm.id}'")
        for dep in self.dependencies:
            record_id(dep.id, f"Dependency '{dep.id}'")
        for cq in self.clarification_questions:
            record_id(cq.id, f"Clarification Question '{cq.id}'")

        # 3. Referential integrity
        valid_req_ids = set()
        for fr in self.functional_requirements:
            valid_req_ids.add(fr.id)
        for nfr in self.non_functional_requirements:
            valid_req_ids.add(nfr.id)

        # Validate user story references
        for us in self.user_stories:
            for rel_id in us.related_requirement_ids:
                if rel_id not in valid_req_ids:
                    raise ValueError(
                        f"Referential integrity failure: User Story '{us.id}' references non-existent "
                        f"requirement ID '{rel_id}'. Must reference one of {sorted(valid_req_ids)}."
                    )

        # Validate business rule references
        for br in self.business_rules:
            for rel_id in br.related_requirement_ids:
                if rel_id not in valid_req_ids:
                    raise ValueError(
                        f"Referential integrity failure: Business Rule '{br.id}' references non-existent "
                        f"requirement ID '{rel_id}'. Must reference one of {sorted(valid_req_ids)}."
                    )

        # Validate dependency references
        for dep in self.dependencies:
            if dep.source_id not in valid_req_ids:
                raise ValueError(
                    f"Referential integrity failure: Dependency '{dep.id}' source_id '{dep.source_id}' "
                    f"does not exist. Must reference one of {sorted(valid_req_ids)}."
                )
            if dep.target_id not in valid_req_ids:
                raise ValueError(
                    f"Referential integrity failure: Dependency '{dep.id}' target_id '{dep.target_id}' "
                    f"does not exist. Must reference one of {sorted(valid_req_ids)}."
                )
            if dep.source_id == dep.target_id:
                raise ValueError(
                    f"Circular/self dependency detected in Dependency '{dep.id}': "
                    f"source and target both reference '{dep.source_id}'."
                )

        return self

    def apply_review_decision(self, decision: RequirementReviewDecision) -> bool:
        """Find a matching requirement by ID and apply the review decision."""
        for fr in self.functional_requirements:
            if fr.id == decision.target_id:
                fr.apply_decision(decision)
                return True
        for nfr in self.non_functional_requirements:
            if nfr.id == decision.target_id:
                nfr.apply_decision(decision)
                return True
        raise ValueError(f"Requirement proposal with ID '{decision.target_id}' not found in generation result.")

    def get_accepted_requirements(self) -> list[ProposedFunctionalRequirement | ProposedNonFunctionalRequirement]:
        """Return all requirements that have been accepted or modified by the user."""
        accepted: list[ProposedFunctionalRequirement | ProposedNonFunctionalRequirement] = []
        for fr in self.functional_requirements:
            if fr.review_status in (ProposalReviewStatus.ACCEPTED, ProposalReviewStatus.MODIFIED):
                accepted.append(fr)
        for nfr in self.non_functional_requirements:
            if nfr.review_status in (ProposalReviewStatus.ACCEPTED, ProposalReviewStatus.MODIFIED):
                accepted.append(nfr)
        return accepted

    @classmethod
    def from_llm_response(cls, response: LLMResponse, project_id: str) -> RequirementGenerationResult:
        """Parse and validate an LLMResponse into a RequirementGenerationResult."""
        raw_dict = response.structured_output
        if raw_dict is None:
            cleaned = response.content.strip()
            # Strip markdown json codeblock fences if present
            if cleaned.startswith("```json"):
                cleaned = cleaned[len("```json"):].strip()
            if cleaned.startswith("```"):
                cleaned = cleaned[len("```"):].strip()
            if cleaned.endswith("```"):
                cleaned = cleaned[:-len("```")].strip()

            try:
                raw_dict = json.loads(cleaned)
            except json.JSONDecodeError as exc:
                raise GenerationSchemaValidationError(
                    f"Failed to parse LLM response as JSON: {str(exc)}"
                ) from exc

        if not isinstance(raw_dict, dict):
            raise GenerationSchemaValidationError(
                f"LLM output must be a JSON object, got {type(raw_dict).__name__}."
            )

        # Enforce target project_id
        raw_dict["project_id"] = project_id

        try:
            return cls.model_validate(raw_dict)
        except Exception as exc:
            raise GenerationSchemaValidationError(
                f"LLM output failed RequirementGenerationResult schema validation: {str(exc)}"
            ) from exc

    @classmethod
    def from_json(cls, json_str: str, project_id: str) -> RequirementGenerationResult:
        """Parse raw JSON string into a validated RequirementGenerationResult."""
        try:
            raw_dict = json.loads(json_str)
        except json.JSONDecodeError as exc:
            raise GenerationSchemaValidationError(f"Invalid JSON: {str(exc)}") from exc

        if not isinstance(raw_dict, dict):
            raise GenerationSchemaValidationError(
                f"Expected JSON object, got {type(raw_dict).__name__}."
            )

        raw_dict["project_id"] = project_id
        try:
            return cls.model_validate(raw_dict)
        except Exception as exc:
            raise GenerationSchemaValidationError(
                f"Validation error: {str(exc)}"
            ) from exc


def convert_proposal_to_requirement_create(
    proposal: ProposedFunctionalRequirement | ProposedNonFunctionalRequirement,
    allow_draft: bool = False,
) -> RequirementCreate:
    """Safely convert an accepted/modified proposal to an existing RequirementCreate object."""
    return proposal.to_requirement_create(allow_draft=allow_draft)


