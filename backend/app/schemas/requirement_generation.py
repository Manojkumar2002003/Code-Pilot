def utc_now() -> datetime:
    return datetime.now(timezone.utc).replace(tzinfo=None)


class ProposalLifecycleError(Exception):
    """Raised when an invalid review lifecycle transition or conversion is attempted."""
    pass


class RequirementAnalystError(Exception):
    """Base exception for Requirement Analyst Engine operations."""
    pass


class InsufficientContextError(RequirementAnalystError):
    """Raised when project context lacks sufficient detail for meaningful requirement generation."""
    pass


class ContextWindowExceededError(RequirementAnalystError):
    """Raised when context and generation instructions exceed the target model's context window."""
    pass


class GenerationSchemaValidationError(RequirementAnalystError):
    """Raised when an LLM output fails schema validation or referential integrity."""
    pass


class GenerationMode(str, Enum):
    """Operating mode for requirement generation runs."""

    INITIAL = "initial"
    REFINEMENT = "refinement"
    REGENERATION = "regeneration"


class GenerationExecutionMetadata(BaseModel):
    """Execution telemetry recorded during requirement generation."""

    model_config = ConfigDict(extra="forbid")

    generation_mode: GenerationMode = GenerationMode.INITIAL
    initial_provider: LLMProviderID | None = None
    initial_model: str | None = None
    final_provider: LLMProviderID | None = None
    final_model: str | None = None
    failover_occurred: bool = False
    duration_seconds: float = 0.0
    repair_attempts: int = 0
    structured_output_validated: bool = True
    token_usage: TokenUsage | None = None
    failure_category: str | None = None


class ProposalReviewStatus(str, Enum):
    """Review lifecycle status for AI-generated proposals before persistence."""

    DRAFT = "draft"
    ACCEPTED = "accepted"
    REJECTED = "rejected"
    MODIFIED = "modified"


class NFRCategory(str, Enum):
    """Standard quality attribute categories for non-functional requirements."""

    PERFORMANCE = "performance"
    SECURITY = "security"
    RELIABILITY = "reliability"
    SCALABILITY = "scalability"
    ACCESSIBILITY = "accessibility"
    MAINTAINABILITY = "maintainability"
    AVAILABILITY = "availability"
    COMPLIANCE = "compliance"


class RuleProvenance(str, Enum):
    """Distinguishes user-specified business constraints from model-inferred rules."""

    USER_EXPLICIT = "user_explicit"
    MODEL_INFERRED = "model_inferred"


class ReviewDecision(str, Enum):
    """Decision actions applicable to a proposed requirement during user review."""

    ACCEPT = "accept"
    REJECT = "reject"
    MODIFY = "modify"
    RESET_TO_DRAFT = "reset_to_draft"


class ProposedFunctionalRequirement(BaseModel):
    """A proposed functional requirement generated by the AI agent."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    id: str = Field(..., min_length=1, max_length=64, description="Stable identifier (e.g. FR-1).")
    title: str = Field(..., min_length=1, max_length=200)
    description: str = Field(..., min_length=1, max_length=5000)
    expected_behavior: str = Field(
        ...,
        min_length=1,
        max_length=5000,
        description="Detailed expected system response or behavior.",
    )
    actor: str | None = Field(
        default=None,
        max_length=100,
        description="User role or external system triggering this requirement.",
    )
    priority: RequirementPriority = Field(default=RequirementPriority.MEDIUM)
    acceptance_criteria: list[str] = Field(
        default_factory=list,
        description="Measurable conditions for verification.",
    )
    dependencies: list[str] = Field(
        default_factory=list,
        description="IDs of other proposed requirements this depends upon.",
    )
    assumptions: list[str] = Field(
        default_factory=list,
        description="Assumptions made by the model during generation.",
    )
    unresolved_questions: list[str] = Field(
        default_factory=list,
        description="Open questions or ambiguities requiring clarification.",
    )
    review_status: ProposalReviewStatus = Field(
        default=ProposalReviewStatus.DRAFT,
        description="Review lifecycle state.",
    )
    review_notes: str | None = Field(
        default=None,
        max_length=2000,
        description="Human reviewer comments or notes.",
    )

    @field_validator("id")
    @classmethod
    def validate_id(cls, value: str) -> str:
        cleaned = value.strip()
        if not cleaned:
            raise ValueError("Functional requirement identifier cannot be empty.")
        return cleaned

    @field_validator("title")
    @classmethod
    def validate_title(cls, value: str) -> str:
        cleaned = value.strip()
        if not cleaned:
            raise ValueError("Requirement title cannot be empty.")
        return cleaned

    @field_validator("description")
    @classmethod
    def validate_description(cls, value: str) -> str:
        cleaned = value.strip()
        if not cleaned:
            raise ValueError("Requirement description cannot be empty.")
        return cleaned

    @field_validator("expected_behavior")
    @classmethod
    def validate_expected_behavior(cls, value: str) -> str:
        cleaned = value.strip()
        if not cleaned:
            raise ValueError("Expected behavior cannot be empty.")
        return cleaned

    def apply_decision(self, decision: RequirementReviewDecision) -> None:
        """Apply a user review decision and update the proposal state."""
        if decision.target_id != self.id:
            raise ValueError(f"Decision target {decision.target_id} does not match requirement {self.id}")

        if decision.decision == ReviewDecision.ACCEPT:
            self.review_status = ProposalReviewStatus.ACCEPTED
        elif decision.decision == ReviewDecision.REJECT:
            self.review_status = ProposalReviewStatus.REJECTED
        elif decision.decision == ReviewDecision.MODIFY:
            self.review_status = ProposalReviewStatus.MODIFIED
            if decision.modified_title:
                self.title = decision.modified_title
            if decision.modified_description:
                self.description = decision.modified_description
            if decision.modified_priority:
                self.priority = decision.modified_priority
            if decision.modified_acceptance_criteria is not None:
                self.acceptance_criteria = decision.modified_acceptance_criteria
        elif decision.decision == ReviewDecision.RESET_TO_DRAFT:
            self.review_status = ProposalReviewStatus.DRAFT

        if decision.notes:
            self.review_notes = decision.notes

    def to_requirement_create(self, allow_draft: bool = False) -> RequirementCreate:
        """Convert an accepted/modified proposal into the persisted RequirementCreate schema."""
        if not allow_draft and self.review_status not in (
            ProposalReviewStatus.ACCEPTED,
            ProposalReviewStatus.MODIFIED,
        ):
            raise ProposalLifecycleError(
                f"Cannot persist requirement proposal '{self.id}' with status '{self.review_status.value}'. "
                f"Only accepted or modified proposals can be saved to the database."
            )
        return RequirementCreate(
            title=self.title,
            description=self.description,
            type=RequirementType.FUNCTIONAL,
            priority=self.priority,
        )


